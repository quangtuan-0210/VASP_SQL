"""
Repair Result, Status, and Verification Gate structures for VASP-SQL.
"""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class RepairStatus(str, Enum):
    UNCHANGED = "UNCHANGED"   # Original query is valid; no modification needed.
    REPAIRED = "REPAIRED"     # Successfully patched and verified through all gates.
    ABSTAIN = "ABSTAIN"       # Insufficient confidence/evidence or gates failed; refused to patch.


class GateType(str, Enum):
    GATE_A_PARSE = "GATE_A_PARSE"                     # Parse and syntactic reconstruction
    GATE_B_SCHEMA_SCOPE = "GATE_B_SCHEMA_SCOPE"       # Schema existence and scope binding
    GATE_C_TYPE = "GATE_C_TYPE"                       # Type and expression constraint compatibility
    GATE_D_SAFETY = "GATE_D_SAFETY"                   # Read-only and sandbox execution safety
    GATE_E_EXECUTION = "GATE_E_EXECUTION"             # Sandbox execution and result verification
    GATE_F_INTENT = "GATE_F_INTENT"                   # Query intent alignment with natural question


class GateResult(BaseModel):
    gate: GateType = Field(description="Gate identifier.")
    passed: bool = Field(description="Whether the candidate passed this gate.")
    confidence: float = Field(default=1.0, ge=0.0, le=1.0, description="Confidence score [0.0, 1.0].")
    message: Optional[str] = Field(default=None, description="Diagnostic or validation message.")
    details: Dict[str, Any] = Field(default_factory=dict, description="Detailed verification metrics.")


class ASTPatchRecord(BaseModel):
    patch_type: str = Field(description="Type of patch applied: e.g. ReplaceColumn, AddJoin, ReplaceTable.")
    target_node_id: Optional[str] = Field(default=None, description="Identifier of the target AST node.")
    original_fragment: str = Field(description="Original SQL code fragment.")
    replacement_fragment: str = Field(description="Replaced SQL code fragment.")
    reason: str = Field(description="Diagnosis reason that triggered this patch.")
    evidence: str = Field(description="Supporting evidence (schema, FK, execution error, etc.).")


class RepairResult(BaseModel):
    status: RepairStatus = Field(description="Final repair decision: UNCHANGED, REPAIRED, or ABSTAIN.")
    final_sql: str = Field(description="The final SQL query to be executed.")
    original_sql: str = Field(description="The original input SQL generated by the agent.")
    patches_applied: List[ASTPatchRecord] = Field(
        default_factory=list,
        description="List of localized AST patches applied to produce final_sql."
    )
    gate_results: List[GateResult] = Field(
        default_factory=list,
        description="Results of each verification gate executed."
    )
    confidence: float = Field(
        default=1.0,
        ge=0.0,
        le=1.0,
        description="Aggregated confidence score of the final result."
    )
    abstain_reason: Optional[str] = Field(
        default=None,
        description="Explanation if status is ABSTAIN."
    )
    metrics: Dict[str, Any] = Field(
        default_factory=dict,
        description="Resource and performance metrics (e.g. latency_ms, llm_calls, ast_diff_size)."
    )

    @property
    def is_changed(self) -> bool:
        return self.status == RepairStatus.REPAIRED and self.final_sql.strip() != self.original_sql.strip()
